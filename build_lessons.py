#!/usr/bin/env python3
"""Split the Episode 1 audio script into short per-topic lesson segments -> lessons-data.js"""
import re, json, sys
src = open(sys.argv[1] if len(sys.argv) > 1 else '/workspace/audio/FIT_Study_Audio_Episode_1.txt', encoding='utf-8').read()
src = re.sub(r'(?m)^\s*\[PAUSE\]\s*$', '', src)
paras = [p.strip() for p in re.split(r'\n\s*\n', src) if p.strip() and p.strip() != '[PAUSE]']
paras = [p for p in paras if not re.fullmatch(r'(\[PAUSE\]\s*)+', p)]
# (paragraph prefix, topic or None to skip, 'QUIZ' to skip)
M = [
 ("Let's start with the balance sheet", "balance"), ("And here is the rule that ties", "equation"),
 ("Now there is one more distinction", "balance"), ("Here is the balance sheet for Skyline", "balance"),
 ("Now, depreciation", "accrual"), ("Next, the income statement", "income"),
 ("One important idea here is called accrual", "accrual"), ("The statement of cash flows", "cashflow"),
 ("Time for your first quiz", None), ("Now we put the statements to work", "liquidity"),
 ("Liquidity first", "liquidity"), ("Next, leverage", "leverage"), ("Profitability. How well", "profit"),
 ("Last family. Efficiency", "efficiency"), ("Now, here is a good habit", "efficiency"),
 ("Let's do a quick quiz", None), ("Now two techniques that your course uses", "hv"),
 ("Now, the Altman Z-score", "altman"), ("Now the last piece for this section", "tenk"),
 ("Final quiz-yourself for accounting", None),
 ("First idea. Opportunity cost", "oppcost"), ("Second idea. Marginal", "marginal"), ("Third idea. Sunk", "sunk"),
 ("The related idea is fixed versus variable", "costs"), ("Time for a quiz-yourself on the basics", None),
 ("Fourth idea. Supply and demand", "sd"), ("Fifth idea. Elasticity", "elasticity"),
 ("Quiz-yourself on supply", None), ("Sixth idea. Market structures", "structures"),
 ("Now, basic pricing", "pricing"), ("Time to quiz yourself on market", None),
 ("Seventh idea. Game theory", "game"), ("Quiz-yourself on game", None),
 ("Eighth idea. Asymmetric", "asymmetric"), ("Ninth and final idea", "incentives"),
 ("Last quiz-yourself", None), ("Now let's bring it all home", None),
]
cur = None; out = {}
for p in paras:
    for pre, t in M:
        if p.startswith(pre):
            cur = t; break
    else:
        pass
    if cur is None: continue
    out.setdefault(cur, []).append(p)
def chunks(text, limit=420):
    sents = re.split(r'(?<=[.!?])\s+', text); res = []; buf = ''
    for s in sents:
        if buf and len(buf) + len(s) + 1 > limit: res.append(buf); buf = s
        else: buf = (buf + ' ' + s).strip()
    if buf: res.append(buf)
    return res
data = {}
for t, ps in out.items():
    segs = []
    for p in ps:
        p = re.sub(r'^(Part one, )', '', p)
        segs += chunks(p)
    data[t] = segs
js = "/* generated by build_lessons.py from the Episode 1 audio script */\n(function(r,f){if(typeof module==='object'&&module.exports)module.exports=f();else r.LessonData=f();})(typeof self!=='undefined'?self:this,function(){return " + json.dumps(data, indent=1, ensure_ascii=False) + ";});\n"
open('lessons-data.js', 'w', encoding='utf-8').write(js)
print({k: len(v) for k, v in data.items()})
