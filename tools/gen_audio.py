#!/usr/bin/env python3
"""Generate one MP3 per clip in tools/audio-plan.json with edge-tts (en-US-AndrewNeural),
re-encode to 32 kbps mono, write audio/<key>.mp3 and audio-manifest.js.
Run:  node tools/build-audio-plan.js && /workspace/ttsenv/bin/python tools/gen_audio.py
Skips clips that already exist, so it is safe to re-run after content edits."""
import asyncio, json, os, subprocess, sys, tempfile
import edge_tts
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
VOICE = "en-US-AndrewNeural"
OUT = os.path.join(ROOT, "audio"); os.makedirs(OUT, exist_ok=True)
plan = json.load(open(os.path.join(ROOT, "tools", "audio-plan.json")))
sem = asyncio.Semaphore(int(os.environ.get("CONC", "8")))
def encode(src, dst):
    subprocess.run(["ffmpeg", "-y", "-loglevel", "error", "-i", src, "-ac", "1", "-ar", "24000", "-codec:a", "libmp3lame", "-b:a", "32k", dst], check=True)
def dur(f):
    return float(subprocess.run(["ffprobe", "-v", "error", "-show_entries", "format=duration", "-of", "csv=p=0", f], capture_output=True, text=True).stdout.strip() or 0)
async def gen(key, text):
    dst = os.path.join(OUT, key + ".mp3")
    if os.path.exists(dst) and os.path.getsize(dst) > 500: return
    if text == "[beep]":
        subprocess.run(["ffmpeg", "-y", "-loglevel", "error", "-f", "lavfi", "-i", "sine=frequency=880:duration=0.5", "-af", "afade=t=out:st=0.35:d=0.15,volume=0.6", "-ac", "1", "-ar", "24000", "-b:a", "32k", dst], check=True); return
    async with sem:
        for a in range(8):
            try:
                tmp = tempfile.mktemp(suffix=".mp3")
                await edge_tts.Communicate(text, VOICE).save(tmp)
                if os.path.getsize(tmp) > 500:
                    d = dur(tmp)
                    if len(text) > 12 and len(text) / max(d, 0.01) > 22:   # edge-tts sometimes returns a truncated clip: reject and retry
                        print("truncated, retrying", key, d, text[:40], flush=True); os.remove(tmp); continue
                    encode(tmp, dst); os.remove(tmp); return
            except Exception as e:
                print("retry", key, repr(e)[:80], flush=True); await asyncio.sleep(1.5 * (a + 1))
        raise RuntimeError("failed " + key + " " + text[:40])
async def main():
    keys = list(plan.items())
    done = 0
    async def one(k, t):
        nonlocal done
        await gen(k, t); done += 1
        if done % 100 == 0: print(done, "/", len(keys), flush=True)
    await asyncio.gather(*[one(k, t) for k, t in keys])
asyncio.run(main())
clips = {}
for k in plan:
    f = os.path.join(OUT, k + ".mp3"); clips[k] = round(dur(f), 2)
# remove stale clips no longer in the plan
for f in os.listdir(OUT):
    if f.endswith(".mp3") and f[:-4] not in plan: os.remove(os.path.join(OUT, f))
open(os.path.join(ROOT, "audio-manifest.js"), "w").write("/* generated by tools/gen_audio.py - clip key -> duration (s). File is audio/<key>.mp3 */\nwindow.AUDIO_MANIFEST = " + json.dumps({"voice": VOICE, "clips": clips}, separators=(",", ":")) + ";\n")
tot = sum(os.path.getsize(os.path.join(OUT, k + ".mp3")) for k in plan)
print("clips", len(plan), "bytes", tot, "minutes", round(sum(clips.values()) / 60, 1))
